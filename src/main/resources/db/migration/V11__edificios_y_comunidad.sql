SELECT 'Pasaxe 29', 'Avenida del Pasaje (A Pasaxe) 29', 'Oleiros (A Coruña)',
       CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
WHERE NOT EXISTS (SELECT 1 FROM buildings);

UPDATE storage_units
SET building_id = (SELECT id FROM buildings ORDER BY id LIMIT 1)
WHERE parent_unit_id IS NULL AND building_id IS NULL;

UPDATE clients
SET building_id = (SELECT id FROM buildings ORDER BY id LIMIT 1)
WHERE building_id IS NULL;
