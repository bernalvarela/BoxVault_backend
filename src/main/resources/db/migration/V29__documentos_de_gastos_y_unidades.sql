-- =====================================================================
-- V29 - documentos en los gastos y en las unidades
-- =====================================================================
--
-- Un gasto puede llevar sus papeles: el justificante del pago, la factura, el
-- recibo (la carta de pago de la tasa de una licencia). Van en
-- expense_documents, con la misma forma que tax_notice_documents.
--
-- Una unidad puede llevar documentos que no son de un pago concreto,
-- agrupados en entradas: unit_document_entries es la entrada (título, fecha,
-- notas) y unit_document_entry_documents sus ficheros, uno o más.
--
-- Los ficheros siguen en documents; los tipos que se usan (JUSTIFICANTE,
-- FACTURA, NOTIFICACION, FOTO, OTRO) ya están en su CHECK.
--
-- Sin BEGIN/COMMIT: la transacción la abre y la cierra Flyway.
-- =====================================================================

CREATE TABLE IF NOT EXISTS expense_documents (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_id   BIGINT NOT NULL REFERENCES expenses (id),
    document_id  BIGINT NOT NULL REFERENCES documents (id),
    CONSTRAINT uk_expense_documents_document UNIQUE (document_id)
);

CREATE INDEX IF NOT EXISTS idx_expense_documents_expense ON expense_documents (expense_id);

CREATE TABLE IF NOT EXISTS unit_document_entries (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    storage_unit_id  BIGINT        NOT NULL REFERENCES storage_units (id),
    title            VARCHAR(150)  NOT NULL,
    entry_date       DATE          NOT NULL,
    notes            VARCHAR(1000),
    created_at       TIMESTAMP(6),
    updated_at       TIMESTAMP(6),
    created_by       VARCHAR(60),
    updated_by       VARCHAR(60)
);

CREATE INDEX IF NOT EXISTS idx_unit_document_entries_unit ON unit_document_entries (storage_unit_id);

CREATE TABLE IF NOT EXISTS unit_document_entry_documents (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id     BIGINT NOT NULL REFERENCES unit_document_entries (id),
    document_id  BIGINT NOT NULL REFERENCES documents (id),
    CONSTRAINT uk_unit_document_entry_documents_document UNIQUE (document_id)
);

CREATE INDEX IF NOT EXISTS idx_unit_document_entry_documents_entry ON unit_document_entry_documents (entry_id);
