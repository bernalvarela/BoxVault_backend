INSERT INTO rental_parties (rental_agreement_id, client_id, role, position)
SELECT r.id, r.co_client_id, 'ARRENDATARIO', 1
FROM rental_agreements r
WHERE r.co_client_id IS NOT NULL
ON CONFLICT DO NOTHING;

