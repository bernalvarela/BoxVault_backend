-- =====================================================================
-- V30 - gastos relacionados con una entrada de documentos de una unidad
-- =====================================================================
--
-- Una entrada ("Notificación de licencia") puede llevar relacionados los gastos
-- que tienen que ver con ella (el pago de la tasa), para que salgan agrupados
-- con sus justificantes. Un gasto va como mucho en una entrada.
--
-- Sin BEGIN/COMMIT: la transacción la abre y la cierra Flyway.
-- =====================================================================

CREATE TABLE IF NOT EXISTS unit_document_entry_expenses (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id    BIGINT NOT NULL REFERENCES unit_document_entries (id),
    expense_id  BIGINT NOT NULL REFERENCES expenses (id),
    CONSTRAINT uk_unit_document_entry_expenses_expense UNIQUE (expense_id)
);

CREATE INDEX IF NOT EXISTS idx_unit_document_entry_expenses_entry ON unit_document_entry_expenses (entry_id);
