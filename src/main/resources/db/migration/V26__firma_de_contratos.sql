-- =====================================================================
-- V26 - la firma electrónica de los contratos, dentro de BoxVault
-- =====================================================================
--
-- contract_signings: una firma de un contrato (de entrada o de salida), con el
-- PDF que se congela al prepararla y su huella, los huecos de firma que dejó
-- el pie de firmas y, al acabar, el PDF firmado y sellado.
--
-- contract_signers: quién tiene que firmar, con su nombre y su NIF copiados en
-- ese momento, la huella de su enlace (nunca el enlace) y lo que quedó de su
-- firma: cuándo, cómo, desde dónde y si se comprobó su DNI.
--
-- signing_events: el registro de todo lo anterior, encadenado por huellas.
-- Sin FK a propósito, como tax_filings: el registro tiene que sobrevivir.
--
-- Sin BEGIN/COMMIT: la transacción la abre y la cierra Flyway.
-- =====================================================================

CREATE TABLE IF NOT EXISTS contract_signings (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_agreement_id   BIGINT       NOT NULL REFERENCES rental_agreements (id),
    kind                  VARCHAR(10)  NOT NULL,
    status                VARCHAR(12)  NOT NULL DEFAULT 'EN_CURSO',
    original_document_id  BIGINT       NOT NULL REFERENCES documents (id),
    original_sha256       VARCHAR(64)  NOT NULL,
    slots                 TEXT,
    signed_document_id    BIGINT       REFERENCES documents (id),
    prepared_by_user_id   BIGINT       NOT NULL,
    completed_at          TIMESTAMP(6) WITH TIME ZONE,
    cancelled_at          TIMESTAMP(6) WITH TIME ZONE,
    cancel_reason         VARCHAR(255),
    created_at            TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMP(6),
    created_by            VARCHAR(60),
    updated_by            VARCHAR(60),
    CONSTRAINT contract_signings_kind_check CHECK (kind IN ('ENTRADA', 'SALIDA')),
    CONSTRAINT contract_signings_status_check CHECK (status IN ('EN_CURSO', 'COMPLETADA', 'CANCELADA'))
);

CREATE INDEX IF NOT EXISTS idx_contract_signings_rental ON contract_signings (rental_agreement_id);

-- Una sola firma en curso por contrato y tipo: dos a la vez acabarían con dos
-- PDF firmados distintos del mismo contrato.
CREATE UNIQUE INDEX IF NOT EXISTS ux_contract_signings_in_progress
    ON contract_signings (rental_agreement_id, kind) WHERE status = 'EN_CURSO';

CREATE TABLE IF NOT EXISTS contract_signers (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signing_id           BIGINT       NOT NULL REFERENCES contract_signings (id),
    position             INTEGER      NOT NULL,
    role                 VARCHAR(12)  NOT NULL,
    role_number          INTEGER      NOT NULL,
    owner_id             BIGINT,
    client_id            BIGINT,
    on_behalf_of         VARCHAR(150),
    full_name            VARCHAR(150) NOT NULL,
    tax_id               VARCHAR(20),
    email                VARCHAR(150),
    phone                VARCHAR(30),
    token_hash           VARCHAR(64),
    token_created_at     TIMESTAMP(6) WITH TIME ZONE,
    token_expires_at     TIMESTAMP(6) WITH TIME ZONE,
    failed_attempts      INTEGER      NOT NULL DEFAULT 0,
    link_opened_at       TIMESTAMP(6) WITH TIME ZONE,
    signed_at            TIMESTAMP(6) WITH TIME ZONE,
    channel              VARCHAR(12),
    signed_ip            VARCHAR(64),
    signed_user_agent    VARCHAR(400),
    signature_key        VARCHAR(255),
    signature_sha256     VARCHAR(64),
    document_sha256      VARCHAR(64),
    identity_checked     BOOLEAN      NOT NULL DEFAULT FALSE,
    identity_checked_by  VARCHAR(60),
    witnessed_by         VARCHAR(60),
    CONSTRAINT contract_signers_role_check CHECK (role IN ('ARRENDADOR', 'ARRENDATARIO', 'FIADOR')),
    CONSTRAINT contract_signers_channel_check CHECK (channel IS NULL OR channel IN ('PRESENCIAL', 'ENLACE'))
);

CREATE INDEX IF NOT EXISTS idx_contract_signers_signing ON contract_signers (signing_id);
CREATE UNIQUE INDEX IF NOT EXISTS ux_contract_signers_token ON contract_signers (token_hash);

CREATE TABLE IF NOT EXISTS signing_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signing_id   BIGINT       NOT NULL,
    signer_id    BIGINT,
    type         VARCHAR(20)  NOT NULL,
    happened_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    actor        VARCHAR(60),
    ip           VARCHAR(64),
    user_agent   VARCHAR(400),
    detail       VARCHAR(500),
    prev_hash    VARCHAR(64),
    hash         VARCHAR(64)  NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_signing_events_signing ON signing_events (signing_id, id);
