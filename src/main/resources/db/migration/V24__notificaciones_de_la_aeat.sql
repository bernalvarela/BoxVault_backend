-- =====================================================================
-- V24 - las notificaciones de la AEAT: requerimientos, sanciones, recargos
-- =====================================================================
--
-- Una notificación va con el titular, el modelo y el ejercicio a los que se
-- refiere (la sanción por presentar tarde el 184 de la comunidad de bienes) y,
-- si está registrada, con la declaración presentada. Guarda sus plazos, el
-- importe y el reducido por pronto pago, y el gasto con el que se pagó.
--
-- filing_id, owner_id y expense_id van sin FK, igual que en tax_filings: la
-- notificación tiene que sobrevivir a que se borre la declaración, el titular
-- o el gasto.
--
-- Sus documentos, en tax_notice_documents, con un tipo nuevo: NOTIFICACION.
-- Y el pago, como gasto de la categoría SANCIONES (la columna category es
-- texto, no hace falta tocarla).
--
-- Sin BEGIN/COMMIT: la transacción la abre y la cierra Flyway.
-- =====================================================================

CREATE TABLE IF NOT EXISTS tax_notices (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind               VARCHAR(30)  NOT NULL,
    status             VARCHAR(20)  NOT NULL DEFAULT 'PENDIENTE',
    model              VARCHAR(20),
    tax_year           INTEGER,
    tax_quarter        INTEGER,
    owner_id           BIGINT,
    owner_name         VARCHAR(150),
    filing_id          BIGINT,
    reference          VARCHAR(100),
    description        VARCHAR(255),
    received_on        DATE         NOT NULL,
    response_deadline  DATE,
    payment_deadline   DATE,
    amount             NUMERIC(12,2),
    reduced_amount     NUMERIC(12,2),
    paid_on            DATE,
    paid_amount        NUMERIC(12,2),
    expense_id         BIGINT,
    notes              TEXT,
    created_at         TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP(6),
    created_by         VARCHAR(60),
    updated_by         VARCHAR(60),
    CONSTRAINT tax_notices_kind_check CHECK (kind IN (
        'REQUERIMIENTO', 'PROPUESTA_SANCION', 'SANCION', 'RECARGO', 'APREMIO', 'OTRO')),
    CONSTRAINT tax_notices_status_check CHECK (status IN ('PENDIENTE', 'RECURRIDA', 'PAGADA', 'CERRADA'))
);

CREATE INDEX IF NOT EXISTS idx_tax_notices_received ON tax_notices (received_on DESC);
CREATE INDEX IF NOT EXISTS idx_tax_notices_filing ON tax_notices (filing_id);

CREATE TABLE IF NOT EXISTS tax_notice_documents (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tax_notice_id  BIGINT NOT NULL REFERENCES tax_notices (id),
    document_id    BIGINT NOT NULL REFERENCES documents (id),
    CONSTRAINT uk_tax_notice_documents_document UNIQUE (document_id)
);

CREATE INDEX IF NOT EXISTS idx_tax_notice_documents_notice ON tax_notice_documents (tax_notice_id);

ALTER TABLE documents DROP CONSTRAINT IF EXISTS documents_document_type_check;
ALTER TABLE documents ADD CONSTRAINT documents_document_type_check CHECK (document_type IN (
    'DNI', 'CONTRATO_TRABAJO', 'NOMINA', 'FOTO',
    'CONTRATO_ALQUILER', 'CONTRATO_SALIDA', 'ANEXO', 'FACTURA',
    'IGVS_ARRENDADOR', 'IGVS_ARRENDATARIO', 'IGVS_DEVOLUCION',
    'JUSTIFICANTE', 'DECLARACION', 'NOTIFICACION', 'OTRO'));
